# Task 2: Exploring Primitive Data Types

# Integer
my_int = 17

# Float
my_float = 4.5

# String
my_str = "Python is awesome!"

# Boolean
my_bool = True

# Print types and values
print("Integer value:", my_int, "| Type:", type(my_int))
print("Float value:", my_float, "| Type:", type(my_float))
print("String value:", my_str, "| Type:", type(my_str))
print("Boolean value:", my_bool, "| Type:", type(my_bool))
